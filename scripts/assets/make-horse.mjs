// Original low-poly horse mesh for the Wee build splash. Run to regenerate OBJ.
import fs from 'node:fs';
const lines = ['# Original Wee horse; generated by make-horse.mjs', 'mtllib horse.mtl'];
let count = 0;
function shape(name, center, scale, material = 'coat', tilt = 0, rings = 5, sides = 8) {
  lines.push(`o ${name}`, `usemtl ${material}`);
  const start = count + 1;
  for (let j = 0; j <= rings; j++) {
    const lat = Math.PI * j / rings;
    for (let i = 0; i < sides; i++) {
      const lon = 2 * Math.PI * i / sides;
      const x = scale[0] * Math.sin(lat) * Math.cos(lon);
      const y = scale[1] * Math.cos(lat);
      const z = scale[2] * Math.sin(lat) * Math.sin(lon);
      lines.push(`v ${(center[0] + x*Math.cos(tilt)-y*Math.sin(tilt)).toFixed(4)} ${(center[1] + x*Math.sin(tilt)+y*Math.cos(tilt)).toFixed(4)} ${(center[2]+z).toFixed(4)}`);
      count++;
    }
  }
  for (let j = 0; j < rings; j++) for (let i = 0; i < sides; i++) {
    const a=start+j*sides+i, b=start+j*sides+(i+1)%sides, c=b+sides, d=a+sides;
    lines.push(`f ${a} ${d} ${c}`, `f ${a} ${c} ${b}`);
  }
}
shape('body', [0,1.6,0], [1.15,.55,.43]);
shape('chest', [.72,1.7,0], [.48,.64,.42]);
shape('neck', [1.02,2.23,0], [.35,.87,.3], 'coat', -.42);
shape('head', [1.5,2.96,0], [.48,.3,.26], 'coat', -.2);
shape('muzzle', [1.84,2.8,0], [.34,.23,.24], 'muzzle', -.2);
shape('mane', [.76,2.39,0], [.12,.72,.31], 'dark', -.42);
for (const z of [-.18,.18]) {
  shape(`ear${z}`, [1.33,3.34,z], [.10,.31,.10], 'coat', .12, 3, 5);
  shape(`eye${z}`, [1.62,3.02,z < 0 ? -.248 : .248], [.046,.054,.025], 'dark', 0, 3, 6);
}
for (const x of [-.76,.76]) for (const z of [-.29,.29]) {
  const shift = z < 0 ? .12 : -.12;
  shape(`upper-leg${x}${z}`, [x+shift,1.05,z], [.19,.52,.18], 'coat', x < 0 ? -.12 : .06);
  shape(`lower-leg${x}${z}`, [x+shift,.46,z], [.10,.43,.10], 'coat', -.08);
  shape(`hoof${x}${z}`, [x+shift+.035,.11,z], [.17,.13,.135], 'dark', 0, 3, 6);
}
shape('tail', [-1.2,1.41,0], [.15,.68,.17], 'dark', -.38);
fs.writeFileSync(new URL('horse.obj', import.meta.url), lines.join('\n')+'\n');
